naoCasados AS (
  SELECT * FROM planilha p
   WHERE NOT EXISTS (
     SELECT 1 FROM "Produto" pr WHERE pr.ativo AND upper(regexp_replace(translate(btrim(pr.nome), 'áàâãäéèêëíìîïóòôõöúùûüçÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇ', 'aaaaaeeeeiiiiooooouuuucAAAAAEEEEIIIIOOOOOUUUUC'), '[^a-zA-Z0-9]+', ' ', 'g')) = p.chave
   )
)
SELECT n.chave AS insumo_da_ficha, n.usos AS fichas_que_usam,
       (SELECT string_agg(x.nome, ' | ' ORDER BY length(x.nome))
          FROM (
            SELECT pr.nome FROM "Produto" pr
             WHERE pr.ativo
               AND upper(regexp_replace(translate(btrim(pr.nome), 'áàâãäéèêëíìîïóòôõöúùûüçÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇ', 'aaaaaeeeeiiiiooooouuuucAAAAAEEEEIIIIOOOOOUUUUC'), '[^a-zA-Z0-9]+', ' ', 'g')) LIKE '%' || n.termo1 || '%'
               AND upper(regexp_replace(translate(btrim(pr.nome), 'áàâãäéèêëíìîïóòôõöúùûüçÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇ', 'aaaaaeeeeiiiiooooouuuucAAAAAEEEEIIIIOOOOOUUUUC'), '[^a-zA-Z0-9]+', ' ', 'g')) LIKE '%' || n.termo2 || '%'
             LIMIT 5
          ) x) AS candidatos
  FROM naoCasados n
 ORDER BY n.usos DESC, n.chave;
