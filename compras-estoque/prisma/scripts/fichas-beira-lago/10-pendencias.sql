    JOIN "Unidade" u ON u.nome = 'Beira Lago'
    JOIN "Receita" r ON r."unidadeId" = u.id AND upper(regexp_replace(translate(btrim(r.nome), 'áàâãäéèêëíìîïóòôõöúùûüçÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇ', 'aaaaaeeeeiiiiooooouuuucAAAAAEEEEIIIIOOOOOUUUUC'), '[^a-zA-Z0-9]+', ' ', 'g')) = p.ficha
    LEFT JOIN "IngredienteReceita" g ON g."receitaId" = r.id
    LEFT JOIN "Produto" pr ON pr.id = g."produtoId"
    LEFT JOIN "Receita" sub ON sub.id = g."subReceitaId"
   WHERE upper(regexp_replace(translate(btrim(coalesce(pr.nome, sub.nome)), 'áàâãäéèêëíìîïóòôõöúùûüçÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇ', 'aaaaaeeeeiiiiooooouuuucAAAAAEEEEIIIIOOOOOUUUUC'), '[^a-zA-Z0-9]+', ' ', 'g')) = p.esperado
)
SELECT p.ficha, p.ingrediente AS ingrediente_da_planilha, p.quantidade,
       (SELECT string_agg(x.nome, ' | ' ORDER BY length(x.nome))
          FROM (SELECT pr.nome FROM "Produto" pr
                 WHERE pr.ativo
                   AND upper(regexp_replace(translate(btrim(pr.nome), 'áàâãäéèêëíìîïóòôõöúùûüçÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇ', 'aaaaaeeeeiiiiooooouuuucAAAAAEEEEIIIIOOOOOUUUUC'), '[^a-zA-Z0-9]+', ' ', 'g')) LIKE '%' || p.primeira_palavra || '%'
                 LIMIT 4) x) AS produtos_parecidos,
       (SELECT string_agg(x.nome, ' | ' ORDER BY length(x.nome))
          FROM (SELECT r2.nome FROM "Receita" r2
                 JOIN "Unidade" u2 ON u2.id = r2."unidadeId" AND u2.nome = 'Beira Lago'
                 WHERE upper(regexp_replace(translate(btrim(r2.nome), 'áàâãäéèêëíìîïóòôõöúùûüçÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇ', 'aaaaaeeeeiiiiooooouuuucAAAAAEEEEIIIIOOOOOUUUUC'), '[^a-zA-Z0-9]+', ' ', 'g')) LIKE '%' || p.primeira_palavra || '%'
                 LIMIT 3) x) AS fichas_parecidas
  FROM planilha p
 WHERE NOT EXISTS (SELECT 1 FROM gravado g WHERE g.ficha = p.ficha AND g.esperado = p.esperado)
 ORDER BY p.quantidade DESC, p.ficha;
