       CASE
         WHEN pr.id IS NOT NULL THEN 'cadastrado em ' || pr."unidadeMedida" || ' — falta o volume da embalagem'
         ELSE 'nao existe no cadastro'
       END AS motivo
  FROM linha l
  LEFT JOIN "Produto" pr ON pr.ativo AND upper(regexp_replace(translate(btrim(pr.nome), 'áàâãäéèêëíìîïóòôõöúùûüçÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇ', 'aaaaaeeeeiiiiooooouuuucAAAAAEEEEIIIIOOOOOUUUUC'), '[^a-zA-Z0-9]+', ' ', 'g')) = l.chave_produto
 WHERE NOT EXISTS (
   SELECT 1 FROM "Produto" p2
    WHERE p2.ativo AND upper(regexp_replace(translate(btrim(p2.nome), 'áàâãäéèêëíìîïóòôõöúùûüçÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇ', 'aaaaaeeeeiiiiooooouuuucAAAAAEEEEIIIIOOOOOUUUUC'), '[^a-zA-Z0-9]+', ' ', 'g')) = l.chave_produto
