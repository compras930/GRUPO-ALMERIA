-- 1. O PLACAR.
--    `por_codigo`  achou pelo código — o caminho bom.
--    `so_por_nome` o código não achou, o nome sim. São os produtos em que vale
--                  gravar o código no app, para a próxima vez casar direto.
--    `nenhum`      é o cadastro que falta.
SELECT count(*) AS insumos_na_planilha,
       count(*) FILTER (WHERE pc.id IS NOT NULL) AS por_codigo,
       count(*) FILTER (WHERE pc.id IS NULL AND pn.id IS NOT NULL) AS so_por_nome,
       count(*) FILTER (WHERE pc.id IS NULL AND pn.id IS NULL) AS nenhum
FROM _insumos_matri pl
LEFT JOIN "Produto" pc ON pc."codigoTeknisa" = pl.codigo
LEFT JOIN LATERAL (
  SELECT p.id FROM "Produto" p
  WHERE lower(btrim(p.nome)) = lower(btrim(pl.nome)) LIMIT 1
) pn ON true;

-- 2. OS 40 PRIMEIROS QUE NÃO CASARAM DE JEITO NENHUM, para dimensionar o
--    cadastro que falta.
SELECT pl.codigo, pl.nome
FROM _insumos_matri pl
LEFT JOIN "Produto" pc ON pc."codigoTeknisa" = pl.codigo
LEFT JOIN LATERAL (
  SELECT p.id FROM "Produto" p
  WHERE lower(btrim(p.nome)) = lower(btrim(pl.nome)) LIMIT 1
) pn ON true
WHERE pc.id IS NULL AND pn.id IS NULL
ORDER BY pl.nome
LIMIT 40;
