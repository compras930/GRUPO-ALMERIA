JOIN "VendaSemanal" vs ON vs.id = i."vendaSemanalId"
JOIN "Unidade" u ON u.id = vs."unidadeId"
LEFT JOIN "ItemVenda" iv ON iv.id = i."itemVendaId"
WHERE u.nome = 'Beira Lago'
  AND vs."periodoInicio" = DATE '2026-10-06'
